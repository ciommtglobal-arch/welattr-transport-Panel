type I18nContextValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: string, fallback?: string) => string;
};

const I18nContext = createContext<I18nContextValue | null>(null);

function getInitialLocale(): Locale {
  if (typeof window === "undefined") return "tr";
  const stored = window.localStorage.getItem(localeStorageKey);
  return normalizeLocale(stored);
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(getInitialLocale);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.documentElement.dir = locale === "ar" ? "rtl" : "ltr";
    window.localStorage.setItem(localeStorageKey, locale);
  }, [locale]);

  const value = useMemo<I18nContextValue>(
    () => {
      const copy = getLocaleCopy(translations, locale);
      return {
        locale,
        setLocale: setLocaleState,
        t: (key: string, fallback?: string) => copy[key] ?? fallback ?? key,
      };
    },
    [locale],
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n must be used inside I18nProvider");
  return context;
}

export function LanguageSelector() {
  const { locale, setLocale, t } = useI18n();
  return (
    <label className="fixed right-4 top-3 z-[70] flex items-center gap-2 border border-border/70 bg-background/90 px-2 py-1.5 text-[10px] font-semibold uppercase tracking-wider shadow-sm backdrop-blur-md">
      <span className="sr-only">{t("language")}</span>
      <select
        aria-label={t("language")}
        value={locale}
        onChange={(event) => setLocale(event.target.value as Locale)}
        className="bg-transparent text-foreground outline-none"
      >
        <option value="tr">TR</option>
        <option value="en">EN</option>
        <option value="ar">AR</option>
        <option value="ku">KU</option>
        <option value="ru">RU</option>
        <option value="uk">UA</option>
      </select>
    </label>
  );
}